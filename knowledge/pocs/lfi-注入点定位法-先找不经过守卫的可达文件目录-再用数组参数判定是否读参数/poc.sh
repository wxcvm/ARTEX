## 目标
在一个「所有业务页面都被认证守卫拦截」的 Web 应用里，定位任意文件读取(LFI)/文件包含的注入点。

## 核心推理链（不要跳过第 1 步）
1. **先找落脚点，再找注入点**。守卫（302/401/登录检查）通常只包在业务页面上；
   而**配置目录、数据目录**（`/data/`、`/inc/`、`/conf/`、`/config/`）里的文件往往被遗漏，
   能**直接执行/直接下载**。这些文件就是 LFI 的唯一候选面。
   - 判据：**同一个应用里，若 A 类路径返回 302 到登录页、B 类路径返回 200 且有内容**，
     则 B 类 = 未受守卫保护 = 落脚点。
   - 实证：某目标 `/agent/login.php` → 302 守卫，但 `/data/db.php` → **200 并回显 PHP 警告**。

2. **判定落脚点文件「读不读请求参数」**——这是能否变成 LFI 的决定性判据：
   - **数组参数法**：`?x[]=1`。若代码把参数当标量用（`preg_match($p, $_GET['x'])`、
     `include $_GET['x']`、字符串拼接），PHP 会抛 `TypeError`/`Warning`；
     配合 `display_errors=On`（常见于老旧项目）**错误会直接回显到响应里**，泄露路径/行号/函数名。
   - **差分法**：`?a=1` 与 `?a=<随机串>` 的响应体/长度/耗时若无任何差异 ⇒ 该文件不读参数。
   - **实证**：`/data/db.php` 对 `?x[]=1` 响应完全不变（仍是那 2 条 Deprecated 警告）
     ⇒ 该文件不读 `$_GET`，**不是注入点**。

3. **按「include 型文件」特征去搜**：若第 2 步判定某文件读参数，按 LFI 经典参数名验证
   `?file=` / `?page=` / `?tpl=` / `?path=` / `?include=` / `?url=` / `?template=` / `?mod=`。

4. **Windows 目标的穿越写法**（区别于 Linux）：
   - 正斜杠 `../../../../BtSoft/panel/data/admin_path.pl` 与**反斜杠/双写**都要试：
     `..\..\..\..\BtSoft\panel\data\admin_path.pl`、`..%5c..%5c`、`..//..//`、
     `....//....//`、`%2e%2e%2f`、`%252e%252e%252f`。
   - **注意 nginx 会先规范化路径**：若 nginx 层做了 `..` 规范化（实测：`/example.com/../../data/x`
     会被 nginx 归一化后转给后端），则**穿越必须在「应用参数内」完成，不能在 URL 路径上做**
     —— 路径穿越和参数穿越是两回事，别混。

## 结论模板（负结论也要写清）
- 落脚点目录 = `___`；枚举 N 个文件名，命中 `___`；
- 其中读参数的文件 = `___`（用数组参数法验证）；
- LFI 注入点 = 有/无。无则写明「该路径在 ___ 层被断死」。

## 常见误判
- 把「文件能直接访问」当成「有 LFI」——能访问 ≠ 读任意文件，必须该文件**读参数**。
- 把「路径穿越未成功」当成「LFI 不存在」——先确认注入点是否存在，再谈穿越。
- 忽视 `display_errors`：老旧 PHP 项目（如 PHP 7.4 上还在调 `get_magic_quotes_gpc()`）
  常开启错误回显，这是零成本的信息泄露源，优先利用。