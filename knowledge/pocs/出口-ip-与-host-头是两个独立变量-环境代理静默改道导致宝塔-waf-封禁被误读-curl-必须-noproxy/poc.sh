# 出口 IP 决定成败：本机 curl 默认走环境代理 127.0.0.1:17992，一发多即被宝塔 WAF 全站封

## 现象（2026-10-07 实测，同一次会话内前后几分钟）
| 出口 | 请求 | 结果 |
|---|---|---|
| 环境代理 `HTTP_PROXY=http://127.0.0.1:17992`（出口 203.0.113.2） | `curl -k -H "Host: example.com" https://203.0.113.77/` | 200|127841（**正常**） |
| 同上，连续多发（vhost 差异探测 25 站 × 5 发之后） | 同上 + `/example.com` | **000|0（全站断连）** |
| 同上，改直连 `--noproxy "*"` | 同上 + `/example.com` | **200|127841 / 200|3933（立刻恢复）** |
| 直连（本机真实出口） | `https://203.0.113.77/example.com` | 200|3933 |
| 不带 Host 头（任何出口） | `https://203.0.113.77/example.com` | 404|146（默认 vhost 不是本站） |

## 根因判定
1. 目标侧宝塔「网站防火墙」9.8.9 做的是**源 IP 级黑名单**：同一出口连续发敏感/批量请求后被加黑，全站（443 上所有 vhost）对该出口返回断连（000 / 444），**换域名、换 UA、加 XFF 都无效**（前序已逐条证否）。
2. **本机 curl 默认继承环境变量 `HTTP_PROXY`/`HTTPS_PROXY`/`ALL_PROXY`（=http://127.0.0.1:17992）**，所以「你以为的直连」其实在走代理；代理出口被拉黑后，表面上看起来像「目标挂了」或「域名被改名」，**产生互相矛盾的假阴性结论**。
3. 判断是否被封的最快办法：**同一条命令加 `--noproxy "*"` 再发一次**。若恢复 200，则问题在出口 IP，不在目标。

## 处置规范（打本站/同圈子站群必须遵守）
1. **默认一律 `curl --noproxy "*"`（或先 `Remove-Item Env:HTTP_PROXY,Env:HTTPS_PROXY,Env:ALL_PROXY`）**，让请求从本机真实出口出去。
2. 直连出现 000/444 时，才切第三方出口（代理池），**每次请求记录用的是哪个出口**，避免把出口问题记成目标结论。
3. 批量探测要限速（每发间隔 ≥250ms，成片敏感路径如 `/.git/config`、`/.env`、`/www.zip` 一律不要连发 —— 这是上一次被拉黑的直接原因）。
4. 判据：**「Host 头是否带上」和「出口是否被封」是两个独立变量，必须分开验证** —— 不带 Host 头 → 404|146（默认 vhost）；带 Host 头但出口被封 → 000；两者都正常才是 200|3933。

## 通用化
适用于任何「站群 + 按源 IP 封禁的 WAF（宝塔/云 WAF）」目标；同样适用于本机装了 HTTP 代理（clash/v2ray 等）的渗透环境 —— 环境变量代理会让所有 curl 静默改道，是假阴性的常见来源。
