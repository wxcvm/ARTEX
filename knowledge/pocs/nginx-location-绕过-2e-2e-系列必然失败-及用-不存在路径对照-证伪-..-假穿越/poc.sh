## 结论
当 nginx 只放行了部分前缀（本例仅 `location /api/v1/v/` 与 `location /api/v1/t/`），
想用路径穿越访问未放行前缀（`/api/v1/u/`）时：

1. `%2e%2e` / `..%2f` / `%2E%2E` / `../` / `//` / `/./` / 大小写变体 —— **全部无效**。
   nginx 在 location 匹配**之前**就做 URI 归一化（解码 + 去 . / .. + merge_slashes），
   归一化会重新落到未放行前缀上，继续返回 RST。
2. `..;/` 与 `..%3b/`（Tomcat 路径参数分隔符）—— nginx **不**把 `;` 当作分隔符，故可原样透传后端，
   **但实际上并不能跨前缀**：本系统实测被 v 前缀拦截器按前缀拦下。

## 关键判据（避免误判为"穿越成功"）
必须做**不存在的路径对照实验**：

  GET /api/v1/v/..;/zzz/     -> 401 {"code":401,"msg":"暂未登录或token已经过期"}
  GET /api/v1/v/..;/u/       -> 401 （一模一样）

既然连 `zzz` 这种绝不存在的路径都返回同一个 401，说明该 401 来自
**v 前缀 token 拦截器的前缀匹配**，与 `../u/` 是否被后端归一化**无关** —— 穿越未生效。
（若只有 `/..;/u/` 返回 401 而 `/..;/zzz/` 返回应用 404，才是穿越生效的正面证据。）

## 自洽性验证（证明"nginx 先归一化"这一前提）
  GET /api/v1/v/%2e%2e/v/  -> 与真身 GET /api/v1/v/ 响应**逐字节一致**
  GET /api/v1/v/%2e%2e/t/  -> {"code":404,"message":"error 1"}（t 后端的 404 格式）
  GET /api/v1/v/%2e%2e/f/  -> 000 RST（f 未放行 → 归一化后仍被拒）
三条同时成立，即证明归一化发生在 nginx 的 location 匹配之前。

## 失败后应转向哪里
公网面前缀缺失基本无法从 nginx 侧绕过，正确方向是：
- 换入口（同集群其它节点/端口，本例逐个测了 8 台机 × 7 端口）
- 找反向代理后的**后端应用直连端口**
- 找该前缀真正所属的**另一套前端**（客服端/管理端）

## 提示
curl 必须加 `--path-as-is`，否则 curl 自己就把 `../` 归一化了，测试结果无效。
